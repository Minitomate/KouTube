export const STRINGS: Record<Locale, Record<I18nKey, string>> = { en, es };

/** Translate a key, filling {vars}. Missing vars stay as literal {name}. */
export function t(locale: Locale, key: I18nKey, vars?: Record<string, string | number>): string {
  let s: string = STRINGS[locale][key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

