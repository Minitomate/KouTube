// UI locale: English + Spanish, following the OS/browser language in auto mode.
// Single hand-rolled dictionary (no dep): en holds the source strings verbatim,
// es must cover every key (I18nKey makes a missing translation a type error).
// Machine-parsed telemetry notes (speed/ETA chips, server staging lines) stay
// in their stable English shape on purpose: splitStats and the Home ETA logic
// match on those tokens, so producers are never translated — only render text.
export type LocaleSetting = 'auto' | 'en' | 'es';
export type Locale = 'en' | 'es';

export function resolveLocale(setting: LocaleSetting, navLang?: string): Locale {
  if (setting === 'en' || setting === 'es') return setting;
  const nav = navLang ?? (typeof navigator !== 'undefined' ? navigator.language : '');
  return /^es\b/i.test(nav ?? '') ? 'es' : 'en';
}

/** BCP-47 tag for Intl formatting (counts, dates). */
export function localeTag(l: Locale): string {
  return l === 'es' ? 'es-ES' : 'en-US';
}

// Mirror of the settings store key in lib/settings.ts (kept literal here so
// the store and main.ts stay light: settings.ts pulls in the M3 color lib).
const LS_KEY = 'koutube-settings';

/** Stored locale choice without zod/async: 'auto' for anything unreadable. */
export function readLocaleSettingSync(): LocaleSetting {
  try {
    if (typeof localStorage === 'undefined') return 'auto';
    const raw = localStorage.getItem(LS_KEY);
    if (!raw) return 'auto';
    const v: unknown = (JSON.parse(raw) as { locale?: unknown }).locale;
    return v === 'en' || v === 'es' || v === 'auto' ? v : 'auto';
  } catch {
    return 'auto';
  }
}

